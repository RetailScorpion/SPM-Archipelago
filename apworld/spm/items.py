"""The randomizer's items: their names, Archipelago ids and how important each one is.

Most items are game items, listed in data.py (generated by tools/gen_ap_data.py). A few aren't game
items and are added here: the Pure Hearts (each opens a chapter door), the Save Block, the Progressive
Wallets and the Cursya Trap. Every item's Archipelago id is ID_BASE plus its number in the game (or, for the added ones, a
number the mod knows them by).
"""

from BaseClasses import Item, ItemClassification

from .data import ID_BASE, ITEMS

GAME = "Super Paper Mario"

# The goal: an event item placed on the "Chapter 8 complete" location (not a real item)
VICTORY_ITEM = "Victory"

# Pure Hearts 1-7: each opens its chapter's door in Flipside Tower. The mod knows them as numbers
# 1001-1007 (mod/include/pure_hearts.h PURE_HEART_ITEM_FIRST)
HEART_ITEM_FIRST = 1001
TOWER_CHAPTERS = range(1, 8)
HEARTS = {f"Pure Heart {n}": HEART_ITEM_FIRST + n - 1 for n in TOWER_CHAPTERS}
# Pure Heart 8: Chapter 7's vanilla reward. It opens no door, but counts for the castle and final
# requirements (and is the vanilla one)
HEART_8 = "Pure Heart 8"
HEART_8_ID = HEART_ITEM_FIRST + 7

# The Save Block: game item 45, which the mod turns into it (mod/include/save_block.h)
SAVE_BLOCK_ITEM = "Save Block"
SAVE_BLOCK_GAME_ID = 45

# The Cursya Trap: the mod knows it as number 1100 (mod/include/archipelago_item.h TRAP_ITEM_ID)
TRAP_ITEM = "Cursya Trap"
TRAP_GAME_ID = 1100

# Mario: game item 216, an item to find when starting_character isn't Mario (mod starting_character.h)
MARIO_ITEM = "Mario"
MARIO_GAME_ID = 216
CHARACTERS = ["Mario", "Peach", "Bowser", "Luigi"]  # starting_character's order (and the game's)

# Tatl: the game's unused Tippi Pixl (item 220), with tattle_checks (mod tattle_checks.h)
TATL_ITEM = "Tatl"
TATL_GAME_ID = 220

# The Progressive Wallet (progressive_wallet): the mod knows it as number 1200 (mod wallet.h WALLET_ITEM_ID).
# Files start holding 99 coins; three raise it to 200 -> 500 -> 999; with_infinite adds a fourth with no limit
WALLET_ITEM = "Progressive Wallet"
WALLET_GAME_ID = 1200

# The Fire Burst (game item 65): starting as someone else, Flipside's Peach check can need one (rules.py)
FIRE_BURST_ITEM = "Fire Burst"

# What fills empty spots if Archipelago needs more items
FILLER_ITEM = "Shroom Shake"
# The filler made up for locations with no vanilla item of their own (the tattles, the Pure Heart spots)
# and asked for by Archipelago, by weight, in five tiers (user, 2026-11-12)
FILLER_TIERS = (
    (12, ("Shroom Shake", "Cake Mix", "Catch Card", "Horsetail", "Turtley Leaf", "Stop Watch")),
    (7, ("Super Shroom Shake", "Ice Storm", "POW Block", "Big Egg", "Catch Card SP", "Thunder Rage",
         "Peachy Peach", "Volt Shroom")),
    (5, ("Life Shroom", "Shell Shock", "Courage Shell", "Mighty Tonic", "Gold Bar", "Fire Burst", "Hot Sauce",
         "Keel Mango", "Space Food")),
    (3, ("Ghost Shroom", "Gold Bar x3", "Star Medal", "HP Plus", "Power Plus", "Whacka Bump")),
    (1, ("Ultra Shroom Shake", "Shooting Star", "Long-Last Shake", "Gold Medal", "Trial Stew")),
)
FILLER_WEIGHTS = {name: weight for weight, names in FILLER_TIERS for name in names}

# Item categories that can be needed to progress
PROGRESSION_CATEGORIES = ("pixl", "optional_pixl", "key_item", "character")

# Every item name and its Archipelago id
ITEM_NAME_TO_ID = {**{name: ID_BASE + game_id for game_id, (name, _) in ITEMS.items()},
                   **{name: ID_BASE + game_id for name, game_id in HEARTS.items()},
                   HEART_8: ID_BASE + HEART_8_ID,
                   MARIO_ITEM: ID_BASE + MARIO_GAME_ID,
                   TATL_ITEM: ID_BASE + TATL_GAME_ID,
                   TRAP_ITEM: ID_BASE + TRAP_GAME_ID,
                   WALLET_ITEM: ID_BASE + WALLET_GAME_ID,
                   SAVE_BLOCK_ITEM: ID_BASE + SAVE_BLOCK_GAME_ID}


class SPMItem(Item):
    game = GAME


def create_item(name: str, player: int) -> SPMItem:
    """Makes the item called `name` for a player, with its importance (progression, useful, filler
    or trap)."""
    if name == VICTORY_ITEM:
        return SPMItem(name, ItemClassification.progression, None, player)
    if name in HEARTS:
        return SPMItem(name, ItemClassification.progression, ID_BASE + HEARTS[name], player)
    if name == HEART_8:
        return SPMItem(name, ItemClassification.progression, ID_BASE + HEART_8_ID, player)
    if name == TATL_ITEM:
        return SPMItem(name, ItemClassification.progression, ID_BASE + TATL_GAME_ID, player)
    if name == MARIO_ITEM:
        return SPMItem(name, ItemClassification.progression, ID_BASE + MARIO_GAME_ID, player)
    if name == SAVE_BLOCK_ITEM:
        return SPMItem(name, ItemClassification.useful, ID_BASE + SAVE_BLOCK_GAME_ID, player)
    if name == WALLET_ITEM:
        # progression: the Ancient Clue needs a wallet holding 100 coins (rules.NEEDS_100_COIN_WALLET)
        return SPMItem(name, ItemClassification.progression, ID_BASE + WALLET_GAME_ID, player)
    if name == TRAP_ITEM:
        return SPMItem(name, ItemClassification.trap, ID_BASE + TRAP_GAME_ID, player)

    game_id = ITEM_NAME_TO_ID[name] - ID_BASE
    category = ITEMS[game_id][1]
    if category in PROGRESSION_CATEGORIES:
        classification = ItemClassification.progression
    else:
        classification = ItemClassification.filler
    return SPMItem(name, classification, ID_BASE + game_id, player)


def vanilla_item_name(game_id: int) -> str:
    """The item name of a game item id (or of a Pure Heart, 1001-1008)."""
    if game_id >= HEART_ITEM_FIRST:
        return f"Pure Heart {game_id - HEART_ITEM_FIRST + 1}"
    return ITEMS[game_id][0]
