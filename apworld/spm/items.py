"""The randomizer's items: their names, Archipelago ids and how important each one is.

Most items are game items, listed in data.py (generated by tools/gen_ap_data.py). A few aren't game
items and are added here: the Pure Hearts (each opens a chapter door), the Save Block and the Cursya
Trap. Every item's Archipelago id is ID_BASE plus its number in the game (or, for the added ones, a
number the mod knows them by).
"""

from BaseClasses import Item, ItemClassification

from .data import ID_BASE, ITEMS

GAME = "Super Paper Mario"

# The goal: an event item placed on the "Chapter 8 complete" location (not a real item)
VICTORY_ITEM = "Victory"

# Pure Hearts 1-7: each opens its chapter's door in Flipside Tower. The mod knows them as numbers
# 1001-1007 (mod/include/pure_hearts.h PURE_HEART_ITEM_FIRST)
HEART_ITEM_FIRST = 1001
TOWER_CHAPTERS = range(1, 8)
HEARTS = {f"Pure Heart {n}": HEART_ITEM_FIRST + n - 1 for n in TOWER_CHAPTERS}
# Pure Heart 8: Chapter 7's vanilla reward. It doesn't open anything yet (door 8 waits for Chapters 1-7)
HEART_8 = "Pure Heart 8"
HEART_8_ID = HEART_ITEM_FIRST + 7

# The Save Block: game item 45, which the mod turns into it (mod/include/save_block.h)
SAVE_BLOCK_ITEM = "Save Block"
SAVE_BLOCK_GAME_ID = 45

# The Cursya Trap: the mod knows it as number 1100 (mod/include/archipelago_item.h TRAP_ITEM_ID)
TRAP_ITEM = "Cursya Trap"
TRAP_GAME_ID = 1100

# What fills empty spots if Archipelago needs more items
FILLER_ITEM = "Shroom Shake"

# Item categories that can be needed to progress
PROGRESSION_CATEGORIES = ("pixl", "optional_pixl", "key_item", "character")

# Every item name and its Archipelago id
ITEM_NAME_TO_ID = {**{name: ID_BASE + game_id for game_id, (name, _) in ITEMS.items()},
                   **{name: ID_BASE + game_id for name, game_id in HEARTS.items()},
                   HEART_8: ID_BASE + HEART_8_ID,
                   TRAP_ITEM: ID_BASE + TRAP_GAME_ID,
                   SAVE_BLOCK_ITEM: ID_BASE + SAVE_BLOCK_GAME_ID}


class SPMItem(Item):
    game = GAME


def create_item(name: str, player: int) -> SPMItem:
    """Makes the item called `name` for a player, with its importance (progression, useful, filler
    or trap)."""
    if name == VICTORY_ITEM:
        return SPMItem(name, ItemClassification.progression, None, player)
    if name in HEARTS:
        return SPMItem(name, ItemClassification.progression, ID_BASE + HEARTS[name], player)
    if name == HEART_8:
        return SPMItem(name, ItemClassification.useful, ID_BASE + HEART_8_ID, player)
    if name == SAVE_BLOCK_ITEM:
        return SPMItem(name, ItemClassification.useful, ID_BASE + SAVE_BLOCK_GAME_ID, player)
    if name == TRAP_ITEM:
        return SPMItem(name, ItemClassification.trap, ID_BASE + TRAP_GAME_ID, player)

    game_id = ITEM_NAME_TO_ID[name] - ID_BASE
    category = ITEMS[game_id][1]
    if category in PROGRESSION_CATEGORIES:
        classification = ItemClassification.progression
    else:
        classification = ItemClassification.filler
    return SPMItem(name, classification, ID_BASE + game_id, player)


def vanilla_item_name(game_id: int) -> str:
    """The item name of a game item id (or of a Pure Heart, 1001-1008)."""
    if game_id >= HEART_ITEM_FIRST:
        return f"Pure Heart {game_id - HEART_ITEM_FIRST + 1}"
    return ITEMS[game_id][0]
