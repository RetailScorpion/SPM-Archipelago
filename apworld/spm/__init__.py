"""Super Paper Mario (US 1.0) for Archipelago: prototype.

The only logic is the chapter doors: a chapter's locations need its Pure Heart (unless the chapter is
open at the start), Chapter 8's and Peach's need the hearts they wait for. The goal is finishing
Chapter 8.
Locations and items come from data.py, generated by tools/gen_ap_data.py in the project repository.
"""

from BaseClasses import Item, ItemClassification, Location, Region, Tutorial
from Options import OptionError
from worlds.generic.Rules import add_rule
from worlds.AutoWorld import WebWorld, World
from worlds.LauncherComponents import Component, Type, components, launch_subprocess

from .data import ID_BASE, ITEMS, LOCATIONS
from .options import SPMOptions

GAME = "Super Paper Mario"
VICTORY_LOCATION = "Chapter 8 complete"
VICTORY_ITEM = "Victory"

# Location category -> option that shuffles it
CATEGORY_OPTIONS = {
    "pixl": "shuffle_pixls",
    "optional_pixl": "shuffle_optional_pixls",
    "key_item": "shuffle_key_items",
    "overworld_item": "shuffle_overworld_items",
    "catch_card": "shuffle_catch_cards",
    "character": "randomize_characters",
}
# Pure Hearts 1-7: each opens its chapter's door (mod/source/doors.cpp). Not game items: their SPM ids
# are the mod's PURE_HEART_ITEM_FIRST (doors.h) onwards
HEART_ITEM_FIRST = 1001
TOWER_CHAPTERS = range(1, 8)
HEARTS = {f"Pure Heart {n}": HEART_ITEM_FIRST + n - 1 for n in TOWER_CHAPTERS}
TRAP_ITEM = "Cursya Trap"
TRAP_ITEM_SPM = 1100  # mod apitem.h TRAP_ITEM_ID
PEACH_LOCATION = "Flipside/Flopside - Peach joins (mac_02)"  # her scene waits for Chapter 1's end

# Location categories that are never shuffled (the Helmet's gift: Outer Space breaks without it, and
# nothing blocks Chapter 4 without it yet)
FIXED_CATEGORIES = {"fixed"}


def launch_client(*args):
    from .client import main
    launch_subprocess(main, name="SPMClient", args=args)


def launch_patcher(*args):
    from .patcher import launch_patcher as run
    launch_subprocess(run, name="SPMPatcher", args=args)


components.append(Component("Super Paper Mario Client", func=launch_client, component_type=Type.CLIENT))
components.append(Component("Super Paper Mario Patcher", func=launch_patcher, component_type=Type.TOOL))


class SPMItem(Item):
    game = GAME


class SPMLocation(Location):
    game = GAME


class SPMWeb(WebWorld):
    theme = "partyTime"
    tutorials = [Tutorial("Setup Guide", "Setting up the Super Paper Mario prototype.", "English",
                          "setup_en.md", "setup/en", ["RetailScorpion"])]


class SPMWorld(World):
    """Super Paper Mario: flip between dimensions to stop Count Bleck. No-logic prototype."""

    game = GAME
    web = SPMWeb()
    options_dataclass = SPMOptions
    options: SPMOptions
    topology_present = False

    item_name_to_id = {**{name: ID_BASE + spm for spm, (name, _) in ITEMS.items()},
                       **{name: ID_BASE + spm for name, spm in HEARTS.items()},
                       TRAP_ITEM: ID_BASE + TRAP_ITEM_SPM}
    location_name_to_id = {loc[0]: ID_BASE + i for i, loc in enumerate(LOCATIONS)}

    def create_item(self, name: str) -> SPMItem:
        if name == VICTORY_ITEM:
            return SPMItem(name, ItemClassification.progression, None, self.player)
        if name in HEARTS:
            return SPMItem(name, ItemClassification.progression, ID_BASE + HEARTS[name], self.player)
        if name == TRAP_ITEM:
            return SPMItem(name, ItemClassification.trap, ID_BASE + TRAP_ITEM_SPM, self.player)
        spm = self.item_name_to_id[name] - ID_BASE
        category = ITEMS[spm][1]
        if category in ("pixl", "optional_pixl", "key_item", "character"):
            classification = ItemClassification.progression
        else:
            classification = ItemClassification.filler
        return SPMItem(name, classification, ID_BASE + spm, self.player)

    def shuffled(self, category: str) -> bool:
        if category in FIXED_CATEGORIES:
            return False
        return bool(getattr(self.options, CATEGORY_OPTIONS[category]).value)

    def generate_early(self) -> None:
        mode = self.options.starting_chapter_mode
        if mode == mode.option_chosen:
            chapters = {int(key.split()[1]) for key in self.options.starting_chapters.value}
            if not chapters:
                raise OptionError(f"{self.player_name}: Starting Chapters needs at least one chapter")
        else:
            count = (self.options.starting_chapter_count.value if mode == mode.option_random_chapters
                     else self.random.randint(1, len(TOWER_CHAPTERS)))
            chapters = set(self.random.sample(list(TOWER_CHAPTERS), count))
        self.starting_chapters = sorted(chapters)

    def heart_needed(self, chapter: int) -> str | None:
        """The Pure Heart a chapter's locations need, or None if its door is open from the start."""
        return None if chapter in self.starting_chapters else f"Pure Heart {chapter}"

    def create_regions(self) -> None:
        menu = Region("Menu", self.player, self.multiworld)
        for i, (name, _, _, _, _, _) in enumerate(LOCATIONS):
            menu.locations.append(SPMLocation(self.player, name, ID_BASE + i, menu))
        victory = SPMLocation(self.player, VICTORY_LOCATION, None, menu)
        victory.place_locked_item(self.create_item(VICTORY_ITEM))
        menu.locations.append(victory)
        self.multiworld.regions.append(menu)

    def create_items(self) -> None:
        pool, locked = [], []
        for name, _, category, vanilla, _, _ in LOCATIONS:
            item = self.create_item(ITEMS[vanilla][0])
            if self.shuffled(category):
                pool.append(item)
            else:
                locked.append((name, category, item))

        # The Pure Hearts of the chapters that start closed take the place of filler: first from the
        # pool, then by freeing locations that would have kept their vanilla filler
        hearts = [self.create_item(f"Pure Heart {n}") for n in TOWER_CHAPTERS if n not in self.starting_chapters]
        need = len(hearts)
        for item in [item for item in pool if item.classification == ItemClassification.filler][:need]:
            pool.remove(item)
            need -= 1
        freeable = [entry for entry in locked
                    if entry[2].classification == ItemClassification.filler and entry[1] not in FIXED_CATEGORIES]
        freed = set(name for name, _, _ in self.random.sample(freeable, min(need, len(freeable))))
        if len(freed) < need:
            raise OptionError(f"{self.player_name}: not enough locations for {len(hearts)} Pure Hearts")
        for name, _, item in locked:
            if name not in freed:
                self.get_location(name).place_locked_item(item)

        # Traps replace a share of the remaining shuffled filler
        filler = [item for item in pool if item.classification == ItemClassification.filler]
        traps = round(len(filler) * self.options.trap_percentage.value / 100)
        for item in self.random.sample(filler, traps):
            pool.remove(item)
        pool += [self.create_item(TRAP_ITEM) for _ in range(traps)]
        self.multiworld.itempool += pool + hearts

    def set_rules(self) -> None:
        all_hearts = [heart for heart in map(self.heart_needed, TOWER_CHAPTERS) if heart]
        for name, *_ in LOCATIONS:
            chapter = int(name[0]) if name[0].isdigit() and name[1] == "-" else None
            if chapter == 8:
                needed = all_hearts
            elif chapter is not None:
                needed = [self.heart_needed(chapter)]
            elif name == PEACH_LOCATION:
                needed = [self.heart_needed(1)]
            else:
                needed = []
            needed = [heart for heart in needed if heart]
            if needed:
                add_rule(self.get_location(name), lambda state, needed=needed: state.has_all(needed, self.player))
        add_rule(self.get_location(VICTORY_LOCATION), lambda state: state.has_all(all_hearts, self.player))
        self.multiworld.completion_condition[self.player] = lambda state: state.has(VICTORY_ITEM, self.player)

    def get_filler_item_name(self) -> str:
        return "Shroom Shake"

    def fill_slot_data(self) -> dict:
        return {"options": self.options.as_dict(*CATEGORY_OPTIONS.values(), "skip_cutscenes"), "id_base": ID_BASE,
                "starting_chapters": self.starting_chapters}
